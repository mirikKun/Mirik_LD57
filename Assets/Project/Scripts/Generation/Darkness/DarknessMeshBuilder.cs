using System.Collections.Generic;
using UnityEngine;

namespace Project.Scripts.Generation.Darkness
{
    public class DarknessMeshBuilder
    {
        private readonly List<Vector3> _vertices = new List<Vector3>(8192);
        private readonly List<int> _triangles = new List<int>(16384);
        private readonly Vector3[] _cornerPositions = new Vector3[8];
        private readonly float[] _cornerValues = new float[8];
        private readonly Vector3[] _edgeVerts = new Vector3[12];
        private Mesh _mesh;

        public Mesh Mesh
        {
            get
            {
                if (_mesh == null)
                {
                    _mesh = new Mesh { name = "DarknessBubble" };
                    _mesh.indexFormat = UnityEngine.Rendering.IndexFormat.UInt32;
                    _mesh.MarkDynamic();
                }

                return _mesh;
            }
        }

        public void Build(DarknessVolumeField field, Transform meshTransform, float isoLevel = 0.5f)
        {
            _vertices.Clear();
            _triangles.Clear();

            int res = field.Resolution;
            float cell = field.CellSize;
            Vector3 origin = field.Origin;

            for (int z = 0; z < res - 1; z++)
            {
                for (int y = 0; y < res - 1; y++)
                {
                    for (int x = 0; x < res - 1; x++)
                    {
                        PolygoniseCell(field, origin, cell, x, y, z, isoLevel, meshTransform);
                    }
                }
            }

            Mesh mesh = Mesh;
            mesh.Clear();
            mesh.SetVertices(_vertices);
            mesh.SetTriangles(_triangles, 0);
            mesh.RecalculateNormals();
            Vector3 worldCenter = origin + Vector3.one * (res * cell * 0.5f);
            Vector3 localCenter = meshTransform.InverseTransformPoint(worldCenter);
            float localSize = res * cell;
            mesh.bounds = new Bounds(localCenter, Vector3.one * localSize);
        }

        private void PolygoniseCell(
            DarknessVolumeField field,
            Vector3 origin,
            float cell,
            int x,
            int y,
            int z,
            float isoLevel,
            Transform meshTransform)
        {
            _cornerPositions[0] = origin + new Vector3(x * cell, y * cell, z * cell);
            _cornerPositions[1] = origin + new Vector3((x + 1) * cell, y * cell, z * cell);
            _cornerPositions[2] = origin + new Vector3((x + 1) * cell, y * cell, (z + 1) * cell);
            _cornerPositions[3] = origin + new Vector3(x * cell, y * cell, (z + 1) * cell);
            _cornerPositions[4] = origin + new Vector3(x * cell, (y + 1) * cell, z * cell);
            _cornerPositions[5] = origin + new Vector3((x + 1) * cell, (y + 1) * cell, z * cell);
            _cornerPositions[6] = origin + new Vector3((x + 1) * cell, (y + 1) * cell, (z + 1) * cell);
            _cornerPositions[7] = origin + new Vector3(x * cell, (y + 1) * cell, (z + 1) * cell);

            _cornerValues[0] = field.GetDensity(x, y, z);
            _cornerValues[1] = field.GetDensity(x + 1, y, z);
            _cornerValues[2] = field.GetDensity(x + 1, y, z + 1);
            _cornerValues[3] = field.GetDensity(x, y, z + 1);
            _cornerValues[4] = field.GetDensity(x, y + 1, z);
            _cornerValues[5] = field.GetDensity(x + 1, y + 1, z);
            _cornerValues[6] = field.GetDensity(x + 1, y + 1, z + 1);
            _cornerValues[7] = field.GetDensity(x, y + 1, z + 1);

            int cubeIndex = 0;
            if (_cornerValues[0] < isoLevel) cubeIndex |= 1;
            if (_cornerValues[1] < isoLevel) cubeIndex |= 2;
            if (_cornerValues[2] < isoLevel) cubeIndex |= 4;
            if (_cornerValues[3] < isoLevel) cubeIndex |= 8;
            if (_cornerValues[4] < isoLevel) cubeIndex |= 16;
            if (_cornerValues[5] < isoLevel) cubeIndex |= 32;
            if (_cornerValues[6] < isoLevel) cubeIndex |= 64;
            if (_cornerValues[7] < isoLevel) cubeIndex |= 128;

            int edges = EdgeTable[cubeIndex];
            if (edges == 0)
                return;

            if ((edges & 1) != 0) _edgeVerts[0] = VertexInterp(isoLevel, 0, 1);
            if ((edges & 2) != 0) _edgeVerts[1] = VertexInterp(isoLevel, 1, 2);
            if ((edges & 4) != 0) _edgeVerts[2] = VertexInterp(isoLevel, 2, 3);
            if ((edges & 8) != 0) _edgeVerts[3] = VertexInterp(isoLevel, 3, 0);
            if ((edges & 16) != 0) _edgeVerts[4] = VertexInterp(isoLevel, 4, 5);
            if ((edges & 32) != 0) _edgeVerts[5] = VertexInterp(isoLevel, 5, 6);
            if ((edges & 64) != 0) _edgeVerts[6] = VertexInterp(isoLevel, 6, 7);
            if ((edges & 128) != 0) _edgeVerts[7] = VertexInterp(isoLevel, 7, 4);
            if ((edges & 256) != 0) _edgeVerts[8] = VertexInterp(isoLevel, 0, 4);
            if ((edges & 512) != 0) _edgeVerts[9] = VertexInterp(isoLevel, 1, 5);
            if ((edges & 1024) != 0) _edgeVerts[10] = VertexInterp(isoLevel, 2, 6);
            if ((edges & 2048) != 0) _edgeVerts[11] = VertexInterp(isoLevel, 3, 7);

            for (int i = 0; TriTable[cubeIndex, i] != -1; i += 3)
            {
                int i0 = TriTable[cubeIndex, i];
                int i1 = TriTable[cubeIndex, i + 1];
                int i2 = TriTable[cubeIndex, i + 2];
                int baseIndex = _vertices.Count;
                _vertices.Add(meshTransform.InverseTransformPoint(_edgeVerts[i0]));
                _vertices.Add(meshTransform.InverseTransformPoint(_edgeVerts[i1]));
                _vertices.Add(meshTransform.InverseTransformPoint(_edgeVerts[i2]));
                _triangles.Add(baseIndex);
                _triangles.Add(baseIndex + 2);
                _triangles.Add(baseIndex + 1);
            }
        }

        private Vector3 VertexInterp(float isoLevel, int a, int b)
        {
            float va = _cornerValues[a];
            float vb = _cornerValues[b];
            if (Mathf.Abs(isoLevel - va) < 0.00001f)
                return _cornerPositions[a];
            if (Mathf.Abs(isoLevel - vb) < 0.00001f)
                return _cornerPositions[b];
            if (Mathf.Abs(va - vb) < 0.00001f)
                return _cornerPositions[a];

            float mu = (isoLevel - va) / (vb - va);
            return _cornerPositions[a] + mu * (_cornerPositions[b] - _cornerPositions[a]);
        }

